#!/usr/bin/env python3
# Turns a TTF font into gfx_font.h: a small signed distance field per glyph, so the
# Windows/Linux graphics backend (gfx.c) can draw crisp text at any size with no font files.
#   python3 tools/bake_font.py Poppins-Bold.ttf > gfx_font.h      (needs Pillow)
import sys
from PIL import Image, ImageDraw, ImageFont

EM = 24      # glyph size in the atlas, pixels per em
SPREAD = 3   # distances are stored up to this many atlas pixels from the edge
UP = 8       # glyphs are rendered this many times larger, then sampled down
CHARS = [chr(c) for c in range(32, 127)] + list("çÇğĞıİöÖşŞüÜâÂîÎûÛéÉàáèíóúñäßÄ€£°•…–—‘’“”")

INF = 1e20

def edt_1d(f):  # Felzenszwalb & Huttenlocher: squared distance transform of one row
    n = len(f)
    d, v, z = [0.0] * n, [0] * n, [0.0] * (n + 1)
    k, z[0], z[1] = 0, -INF, INF
    for q in range(1, n):
        while True:
            s = ((f[q] + q * q) - (f[v[k]] + v[k] * v[k])) / (2 * q - 2 * v[k])
            if s > z[k]: break
            k -= 1
        k += 1
        v[k], z[k], z[k + 1] = q, s, INF
    k = 0
    for q in range(n):
        while z[k + 1] < q: k += 1
        d[q] = (q - v[k]) ** 2 + f[v[k]]
    return d

def edt(grid, w, h):  # squared distance from each pixel to the nearest pixel where grid is True
    f = [[0.0 if grid[y * w + x] else INF for x in range(w)] for y in range(h)]
    cols = [edt_1d([f[y][x] for y in range(h)]) for x in range(w)]
    return [edt_1d([cols[x][y] for x in range(w)]) for y in range(h)]

def main():
    font = ImageFont.truetype(sys.argv[1], EM * UP)
    ascent, descent = font.getmetrics()
    glyphs, data = [], []
    pad = SPREAD * UP
    for ch in CHARS:
        adv = font.getlength(ch) / UP
        box = font.getbbox(ch)  # relative to the pen, y from the top of the line
        if ch == " " or box[2] <= box[0]:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(data)))
            continue
        x0, y0 = box[0] // UP * UP - pad, box[1] // UP * UP - pad  # align to whole atlas pixels
        w, h = (box[2] - x0 + pad + UP - 1) // UP, (box[3] - y0 + pad + UP - 1) // UP
        img = Image.new("L", (w * UP, h * UP))
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        px = img.load()
        hw, hh = w * UP, h * UP
        inside = [px[x, y] >= 128 for y in range(hh) for x in range(hw)]
        d_out = edt(inside, hw, hh)
        d_in = edt([not i for i in inside], hw, hh)
        off = len(data)
        for ay in range(h):
            for ax in range(w):
                x, y = ax * UP + UP // 2, ay * UP + UP // 2
                sd = (d_in[y][x] ** 0.5 - d_out[y][x] ** 0.5) / UP  # atlas pixels, + inside
                data.append(max(0, min(255, round(128 + sd * 127 / SPREAD))))
        glyphs.append((ord(ch), w, h, x0 // UP, y0 // UP, adv, off))
    print("// Poppins Bold (SIL Open Font License 1.1, see docs/fonts/OFL.txt) as signed distance fields.")
    print("// Generated by tools/bake_font.py; don't edit by hand.")
    print(f"#define FONT_EM {EM}\n#define FONT_SPREAD {SPREAD}\n#define FONT_ASCENT {ascent / UP:.2f}\n#define FONT_DESCENT {descent / UP:.2f}")
    print("static const struct { int cp; short w, h, x, y; float adv; int off; } font_glyphs[] = {")
    for g in glyphs:
        print("  {%d, %d, %d, %d, %d, %.2ff, %d}," % g)
    print("};")
    print("static const unsigned char font_sdf[] = {")
    for i in range(0, len(data), 40):
        print("  " + ",".join(map(str, data[i:i + 40])) + ",")
    print("};")

main()
